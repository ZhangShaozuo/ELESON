import argparse
from pathlib import Path


def main():
    p = argparse.ArgumentParser(description="ELESON raw-data reproduction")
    sub = p.add_subparsers(dest="command", required=True)
    prep = sub.add_parser("prepare", help="audit and align all three raw datasets")
    prep.add_argument("--root", type=Path, default=Path("."))
    prep.add_argument("--output", type=Path, default=Path("cache/review_v3"))
    prep.add_argument("--hz", type=int, default=100)
    prep.add_argument("--seconds", type=float, default=2.)
    prep.add_argument("--stride", type=float, default=2.)
    prep.add_argument("--purity", type=float, default=1.)
    prep.add_argument("--max-gap-ms", type=float, default=100.)
    prep.add_argument("--boundary", choices=["unknown", "neither"], default="unknown")
    prep.add_argument("--frame", choices=["device", "gravity"], default="device")
    prep.add_argument("--limit", type=int)
    prep.add_argument("--diff-start", choices=["drop", "zero"], default="drop")
    prep.add_argument("--acc-scale", type=float, default=9.80665)
    prep.add_argument("--gravity-tau", type=float, default=.5)
    prep.add_argument("--trajectory-offset-ms", type=float, default=0.)
    prep.add_argument("--behavior-threshold", type=float, default=1.5)
    prep.add_argument("--behavior-reducer", choices=["mean", "rms", "max"], default="mean")
    fit = sub.add_parser("train", help="train one fold or all five independent recording folds")
    fit.add_argument("--cache", default="cache/review_v3")
    fit.add_argument("--output", default="runs/eleson")
    fit.add_argument("--fold", default="all")
    fit.add_argument("--folds", type=int, default=5)
    fit.add_argument("--protocol", choices=["recording", "mall"], default="recording")
    fit.add_argument("--holdout-mall")
    fit.add_argument("--sources", nargs="+", choices=["Single_Label_Data", "Segmented_Data", "Trajectory_Data"])
    fit.add_argument("--epochs", type=int, default=100)
    fit.add_argument("--patience", type=int, default=20)
    fit.add_argument("--batch-size", type=int, default=128)
    fit.add_argument("--workers", type=int, default=0)
    fit.add_argument("--threads", type=int, default=4)
    fit.add_argument("--device", default="cpu")
    fit.add_argument("--seed", type=int, default=42)
    fit.add_argument("--lr", type=float, default=1e-3)
    fit.add_argument("--weight-decay", type=float, default=0.)
    fit.add_argument("--normalization", choices=["standard", "none"], default="standard")
    fit.add_argument("--hidden", type=int, default=32)
    fit.add_argument("--frame-samples", type=int, default=10)
    fit.add_argument("--noise-std", type=float, default=.05)
    fit.add_argument("--model-config", help="JSON model options; overrides basic CLI network options")
    fit.add_argument("--loss-config", help="JSON loss options; overrides CLI weights/ablations")
    fit.add_argument("--w1", type=float, default=.6)
    fit.add_argument("--w2", type=float, default=.3)
    fit.add_argument("--w3", type=float, default=.4)
    fit.add_argument("--w4", type=float, default=1.)
    fit.add_argument("--model", choices=["eleson", "e2e"], default="eleson")
    fit.add_argument("--features", choices=["both", "motion", "magnetic"], default="both")
    fit.add_argument("--no-causal", action="store_true")
    fit.add_argument("--no-adversarial", action="store_true")
    fit.add_argument("--no-uncertainty", action="store_true")
    fit.add_argument("--max-steps", type=int, default=0, help="limit batches/epoch for smoke testing only")
    ev = sub.add_parser("evaluate", help="evaluate a checkpoint with its saved training scaler")
    ev.add_argument("--cache", default="cache/review_v3")
    ev.add_argument("--checkpoint", required=True)
    ev.add_argument("--split", choices=["train", "val", "test", "all"], default="test")
    ev.add_argument("--output", default="runs/evaluation")
    ev.add_argument("--batch-size", type=int, default=128)
    ev.add_argument("--threads", type=int, default=4)
    ev.add_argument("--device", default="cpu")
    args = p.parse_args()
    if args.command == "prepare":
        from .data import prepare
        options = vars(args).copy()
        del options["command"]
        prepare(**options)
    else:
        from .engine import train, evaluate
        (train if args.command == "train" else evaluate)(args)


if __name__ == "__main__":
    main()
